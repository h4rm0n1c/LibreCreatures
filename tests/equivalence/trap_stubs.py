#!/usr/bin/env python3
"""Writes trap definitions for the symbols a test does not link.

    trap_stubs.py <linker output> <out.cpp>

The creature tests link creature.cpp, which reaches the skeleton, sound,
display and script code the function under test never calls.  Each symbol
the linker reports undefined (``-Wl,--no-demangle``) gets a function under
that exact name that prints it and exits, so a test that does reach one
fails loudly instead of linking a half-built game.
"""
import re
import sys

text = open(sys.argv[1], errors="replace").read()
names = sorted(set(re.findall(r"undefined reference to `([^']+)'", text)))
with open(sys.argv[2], "w") as out:
    out.write("// Generated by trap_stubs.py: symbols the test does not link.\n")
    out.write("#include <cstdio>\n#include <cstdlib>\n\n")
    out.write("static void equivalence_trap(const char* name) {\n"
              "    std::fprintf(stderr, \"equivalence: reached unlinked %s\\n\", name);\n"
              "    std::exit(6);\n}\n\n")
    for index, name in enumerate(names):
        out.write(f'extern "C" void equivalence_stub_{index}() __asm__("{name}");\n')
        out.write(f'extern "C" void equivalence_stub_{index}() {{ equivalence_trap("{name}"); }}\n')
print(f"{len(names)} trap stubs", file=sys.stderr)
